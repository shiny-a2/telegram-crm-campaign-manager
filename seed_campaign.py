def run():
    db.init()
    c = db.conn()
    with db._LOCK:
        c.execute("DELETE FROM templates")
        c.commit()
    for body in _TEMPLATES:
        db.add_template(body)
    print(f"{len(_TEMPLATES)} قالب کمپین تخفیف جایگزین شد ✅")


if __name__ == "__main__":
    run()
